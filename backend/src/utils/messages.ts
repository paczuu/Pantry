export type MessageCode = keyof typeof MESSAGES;
export type MessageParams = Record<string, string | number>;

/** Fills `{param}` placeholders of the English template. */
const format = (code: MessageCode, params?: MessageParams): string =>
  MESSAGES[code].replace(/\{(\w+)\}/g, (_, key: string) => String(params?.[key] ?? ''));

/** Error payload: spread it into the JSON body, e.g. `res.status(400).json({ ...apiError('NOTE_TITLE_REQUIRED') })`. */
export const apiError = (code: MessageCode, params?: MessageParams) => ({
  error: format(code, params),
  code,
  ...(params ? { params } : {}),
});

/** Success notification payload, spread into the JSON body like {@link apiError}. */
export const apiMessage = (code: MessageCode, params?: MessageParams) => ({
  message: format(code, params),
  messageCode: code,
  ...(params ? { messageParams: params } : {}),
});

/** Audit log `details`: a translatable message plus any extra structured data. */
export const auditDetails = (code: MessageCode, params?: MessageParams, extra: object = {}) => ({
  ...apiMessage(code, params),
  ...extra,
});

/** Error carrying a message code; thrown by validation helpers and turned into a response by controllers. */
export class CodedError extends Error {
  constructor(
    public readonly code: MessageCode,
    public readonly params?: MessageParams
  ) {
    super(format(code, params));
  }
}
